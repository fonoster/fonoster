/**
 * Turns the design library's variables (exported from designs/fonoster.lib.pen
 * into design/tokens.json with the Pencil tools) into src/styles/tokens.css.
 *
 * Names that start with "--" are the shadcn tokens and keep their name. The
 * others (palette and semantic colors) get a "--fn-" prefix so "accent" (mint)
 * doesn't collide with shadcn's "--accent" (hover background).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

type Theme = "light" | "dark";
type Value = string | number;
type Variable = {
  type: "color" | "number" | "string";
  value: Value | { value: Value; theme: { mode: Theme } }[];
};
type Tokens = { variables: Record<string, Variable> };

const THEMES: Theme[] = ["dark", "light"];

function cssName(name: string) {
  return name.startsWith("--") ? name : `--fn-${name}`;
}

function resolve(tokens: Tokens, name: string, theme: Theme, seen: string[] = []): Value {
  const variable = tokens.variables[name];
  if (!variable) throw new Error(`unknown token "${name}" (via ${seen.join(" → ")})`);
  if (seen.includes(name)) throw new Error(`token cycle: ${[...seen, name].join(" → ")}`);

  const raw = Array.isArray(variable.value)
    ? variable.value.find((v) => v.theme.mode === theme)?.value
    : variable.value;
  if (raw === undefined) throw new Error(`token "${name}" has no ${theme} value`);

  return typeof raw === "string" && raw.startsWith("$")
    ? resolve(tokens, raw.slice(1), theme, [...seen, name])
    : raw;
}

function format(variable: Variable, value: Value) {
  if (variable.type === "number") return `${value}px`;
  if (variable.type === "string") return `"${value}"`;
  return String(value).toLowerCase();
}

export function generateTokensCss(tokens: Tokens): string {
  const names = Object.keys(tokens.variables);
  const block = (theme: Theme) =>
    names
      .map((name) => {
        const value = resolve(tokens, name, theme);
        return `  ${cssName(name)}: ${format(tokens.variables[name], value)};`;
      })
      .join("\n");

  const [dark, light] = THEMES.map(block);

  return [
    "/* Generated by scripts/gen-tokens.ts from design/tokens.json. Do not edit. */",
    "",
    ':root,\n[data-theme="dark"] {',
    "  color-scheme: dark;",
    dark,
    "}",
    "",
    '[data-theme="light"] {',
    "  color-scheme: light;",
    light,
    "}",
    ""
  ].join("\n");
}

export const TOKENS_JSON = fileURLToPath(new URL("../design/tokens.json", import.meta.url));
export const TOKENS_CSS = fileURLToPath(new URL("../src/styles/tokens.css", import.meta.url));

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const tokens = JSON.parse(readFileSync(TOKENS_JSON, "utf8")) as Tokens;
  writeFileSync(TOKENS_CSS, generateTokensCss(tokens));
  console.log(`wrote ${TOKENS_CSS}`);
}
